import { expect, test } from '@playwright/test'

test('keyboard separator announces rendered width and Home restores the persisted default', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('canvas')).toBeVisible()
  const left = page.getByTestId('resizer-left')
  const right = page.getByTestId('resizer-right')
  const width = async (side: 'left' | 'right') => Math.round((await page.locator(`.panel.${side}`).boundingBox())!.width)
  const checkWidth = async (side: 'left' | 'right') => {
    const handle = page.getByTestId(`resizer-${side}`)
    await expect.poll(async () => Number(await handle.getAttribute('aria-valuenow'))).toBe(await width(side))
  }
  await expect(left).toHaveAttribute('aria-valuemin', '200')
  await expect(right).toHaveAttribute('aria-valuemin', '240')
  await expect(left).toHaveAttribute('aria-valuemax', '560')
  await expect(right).toHaveAttribute('aria-valuemax', '640')
  await checkWidth('left')
  await checkWidth('right')
  await left.focus()
  await page.keyboard.press('Shift+ArrowRight')
  await expect.poll(() => width('left')).toBe(308)
  await checkWidth('left')
  await right.focus()
  await page.keyboard.press('ArrowLeft')
  await expect.poll(() => width('right')).toBe(336)
  await checkWidth('right')
  await page.setViewportSize({ width: 1120, height: 900 })
  await expect(right).toHaveAttribute('aria-valuemax', '452')
  await checkWidth('right')
  await page.keyboard.press('Home')
  await expect.poll(() => width('right')).toBe(320)
  await checkWidth('right')
  await left.focus()
  await page.keyboard.press('Home')
  await expect.poll(() => width('left')).toBe(260)
  await checkWidth('left')
  await page.reload()
  await expect.poll(() => width('left')).toBe(260)
  await expect.poll(() => width('right')).toBe(320)
  await checkWidth('left')
  await checkWidth('right')
})
