import { expect, test } from '@playwright/test'

test('article import exposes link, paste field and mode choices to keyboard users', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('open-article-import').click()
  const link = page.getByRole('textbox', { name: '文章链接', exact: true })
  await expect(link).toBeVisible()
  await link.fill('https://mp.weixin.qq.com/s/example')
  const pasteMode = page.getByRole('button', { name: /粘贴富文本（公众号/ })
  await pasteMode.focus()
  await pasteMode.press('Enter')
  const paste = page.getByRole('textbox', { name: '粘贴文章富文本', exact: true })
  await expect(paste).toHaveAttribute('aria-multiline', 'true')
  await page.keyboard.press('Tab')
  await expect(paste).toBeFocused()
  await paste.evaluate(el => {
    const data = new DataTransfer()
    data.setData('text/html', '<h2>键盘导入示例</h2><p>普通正文内容。</p>')
    el.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }))
  })
  const group = page.getByRole('group', { name: '导入方式' })
  const keep = group.getByRole('button', { name: '保留原样式' })
  const relayout = group.getByRole('button', { name: '提取内容重新排版' })
  await expect(keep).toHaveAttribute('aria-pressed', 'true')
  await relayout.focus()
  await relayout.press('Space')
  await expect(relayout).toHaveAttribute('aria-pressed', 'true')
  await expect(keep).toHaveAttribute('aria-pressed', 'false')
  await keep.focus()
  await keep.press('Enter')
  await expect(keep).toHaveAttribute('aria-pressed', 'true')
  await expect(relayout).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByTestId('article-import')).toBeDisabled()
  await page.getByTestId('article-authorized').check()
  await expect(page.getByTestId('article-import')).toBeEnabled()
  await page.getByTestId('article-import').click()
  await expect(page.getByTestId('canvas')).toContainText('普通正文内容。')
})
