import { expect, test } from '@playwright/test'

test('cover title supports manual alignment and scoped AI alignment without changing other content', async ({ page }) => {
  await page.route('**/api/ai/status', route => route.fulfill({ json: { enabled: true, name: 'Mock', model: 'mock' } }))
  await page.route('**/api/ai/suggest-instruction', route => route.fulfill({ json: { suggestion: '' } }))
  const requests: any[] = []
  await page.route('**/api/ai/edit', route => {
    const body = route.request().postDataJSON()
    requests.push(body)
    return route.fulfill({ json: { summary: '封面标题居中', ops: [{ op: 'update', id: body.selectedId, props: { titleAlign: 'center' }, reason: '仅调整标题对齐' }] } })
  })
  await page.goto('/')
  await page.getByTestId('tab-projects').click()
  await page.getByRole('button', { name: '新建空白项目' }).click()
  await page.getByTestId('tab-blocks').click()
  await page.getByTestId('lib-cover').click()
  const coverId = await page.getByTestId('canvas').locator('[data-block-type="cover"]').last().getAttribute('data-block-id')
  const cover = page.getByTestId('canvas').locator(`[data-block-id="${coverId}"]`)
  await cover.dblclick()
  const editor = cover.getByTestId('inline-block-text')
  const title = '秋日读书会 在清华园里，与一本书相遇'
  await editor.getByRole('textbox', { name: '标题', exact: true }).fill(title)
  await editor.getByLabel('封面标题对齐').selectOption('center')
  const renderedTitle = cover.locator('.block-html p').filter({ hasText: title })
  await expect(renderedTitle).toHaveCSS('text-align', 'center')
  await editor.getByRole('button', { name: '完成', exact: true }).click()
  const before = await cover.locator('.block-html').innerHTML()
  await page.getByRole('button', { name: '撤销' }).click()
  await expect(renderedTitle).not.toHaveCSS('text-align', 'center')
  await page.getByTestId('tab-style').click()
  await page.locator('.panel.right').getByLabel('封面标题对齐').selectOption('right')
  await expect(renderedTitle).toHaveCSS('text-align', 'right')
  await page.getByTestId('tab-ai').click()
  await expect(page.getByLabel('修改范围')).toHaveValue('selection')
  await page.getByPlaceholder(/例如：把第二章/).fill('标题改为居中')
  await page.getByRole('button', { name: '生成修改建议', exact: true }).click()
  await page.getByTestId('accept-all').click()
  expect(requests[0].selectedId).toBe(await cover.getAttribute('data-block-id'))
  expect(requests[0].context.blocks.find((b: any) => b.id === requests[0].selectedId).type).toBe('cover')
  await expect(renderedTitle).toHaveCSS('text-align', 'center')
  expect(await cover.locator('.block-html').innerHTML()).toBe(before)
  await expect(page.getByTestId('save-status')).toHaveText('已保存', { timeout: 10_000 })
  await page.reload()
  await expect(renderedTitle).toHaveCSS('text-align', 'center')
})
