import { expect, test } from '@playwright/test'

test('contextual ghost text is opt-out, editable, and never auto-submitted', async ({ page }) => {
  const requests: any[] = []
  let edits = 0
  await page.route('**/api/ai/status', route => route.fulfill({ json: { enabled: true, name: 'Mock', model: 'mock', profileId: 'test' } }))
  await page.route('**/api/ai/suggest-instruction', route => {
    requests.push(route.request().postDataJSON())
    return route.fulfill({ json: { suggestion: '精简这段开头，保留活动事实' } })
  })
  await page.route('**/api/ai/edit', route => { edits++; return route.fulfill({ json: { summary: '建议', ops: [] } }) })
  await page.goto('/')
  await page.waitForLoadState('networkidle')
  await page.getByTestId('open-import').click()
  await page.getByTestId('load-sample').click()
  await page.getByTestId('use-ai').uncheck()
  await page.getByTestId('generate').click()
  await page.getByTestId('choose-narrative').click()
  await page.locator('[data-testid=canvas] [data-block-type=paragraph]').first().click()
  await page.getByTestId('tab-ai').click()
  const input = page.getByRole('textbox', { name: 'AI 修改指令' })
  await expect(input).toHaveAttribute('placeholder', '精简这段开头，保留活动事实')
  expect(requests).toHaveLength(1)
  expect(requests[0].context.blocks).toHaveLength(1)
  expect(requests[0].context.blocks[0].id).toBe(requests[0].selectedId)
  await expect(input).toHaveValue('')
  await input.focus()
  await input.press('Tab')
  await expect(input).toHaveValue('精简这段开头，保留活动事实')
  expect(edits).toBe(0)
  await input.fill('我的独立指令')
  await input.press('Tab')
  await expect(input).toHaveValue('我的独立指令')
  await input.fill('')
  await expect(input).toHaveAttribute('placeholder', '精简这段开头，保留活动事实')
  await input.press('Escape')
  await expect(input).not.toHaveAttribute('placeholder', '精简这段开头，保留活动事实')
  await page.getByLabel('自动生成输入建议').uncheck()
  await page.getByTestId('tab-theme').click()
  await page.getByTestId('tab-ai').click()
  await expect(page.getByLabel('自动生成输入建议')).not.toBeChecked()
  await page.getByLabel('修改范围').selectOption('document')
  await page.waitForTimeout(1800)
  expect(requests).toHaveLength(1)
  await input.fill('只改标题')
  await page.getByRole('button', { name: '生成修改建议', exact: true }).click()
  await expect.poll(() => edits).toBe(1)
})

test('model settings changes outside AI tab invalidate a failed suggestion', async ({ page }) => {
  let calls = 0
  await page.route('**/api/ai/status', route => route.fulfill({ json: { enabled: true, name: 'Mock', model: 'mock', profileId: 'test' } }))
  await page.route('**/api/ai/suggest-instruction', route => {
    calls++
    return calls === 1 ? route.fulfill({ status: 503, json: { error: 'invalid credentials' } }) : route.fulfill({ json: { suggestion: '重新生成的输入建议' } })
  })
  await page.goto('/')
  await page.waitForLoadState('networkidle')
  await page.getByTestId('open-import').click()
  await page.getByTestId('load-sample').click()
  await page.getByTestId('use-ai').uncheck()
  await page.getByTestId('generate').click()
  await page.getByTestId('choose-narrative').click()
  await page.getByTestId('tab-ai').click()
  await expect(page.getByRole('status').filter({ hasText: '自动建议暂不可用' })).toBeVisible()
  await page.getByTestId('tab-theme').click()
  // AiSettingsModal dispatches this after saving, including from non-AI tabs.
  await page.evaluate(() => window.dispatchEvent(new Event('ai-settings-changed')))
  await page.getByTestId('tab-ai').click()
  await expect(page.getByRole('textbox', { name: 'AI 修改指令' })).toHaveAttribute('placeholder', '重新生成的输入建议', { timeout: 35_000 })
  expect(calls).toBe(2)
})
