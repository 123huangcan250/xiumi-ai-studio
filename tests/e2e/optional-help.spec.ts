import { test, expect } from '@playwright/test'

test('preview explanation stays hidden until deliberate hover or keyboard focus', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('open-preview').click()
  const dialog = page.getByRole('dialog', { name: '手机预览' })
  const trigger = dialog.getByRole('button', { name: '文章预览说明' })
  const tooltip = page.getByRole('tooltip')
  await expect(trigger).toBeVisible({ timeout: 3000 })
  await expect(tooltip).toHaveCount(0)
  await trigger.hover()
  await expect(tooltip).toHaveCount(0)
  await dialog.getByRole('button', { name: '关闭' }).hover()
  await page.waitForTimeout(750)
  await expect(tooltip).toHaveCount(0)
  await trigger.hover()
  await expect(tooltip).toHaveText('375px 宽度模拟公众号文章页。')
  await page.keyboard.press('Escape')
  await expect(tooltip).toHaveCount(0)
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '关闭' }).focus()
  await page.keyboard.press('Shift+Tab')
  await expect(trigger).toBeFocused()
  await expect(tooltip).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(tooltip).toHaveCount(0)
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})

test('optional help can be toggled at a narrow touch viewport', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true })
  const page = await context.newPage()
  try {
    await page.goto(baseURL!)
    await page.getByTestId('open-preview').click()
    const trigger = page.getByRole('button', { name: '文章预览说明' })
    await trigger.tap()
    const tooltip = page.getByRole('tooltip')
    await expect(tooltip).toBeVisible()
    const box = await tooltip.boundingBox()
    expect(box).not.toBeNull()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(390)
    await trigger.tap()
    await expect(tooltip).toHaveCount(0)
  } finally { await context.close() }
})
