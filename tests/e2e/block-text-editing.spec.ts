import { readFileSync } from 'node:fs'
import { expect, test } from '@playwright/test'

test('double click edits photo text without changing images or editing its parent', async ({ page }) => {
  await page.goto('/')
  const uploaded = await page.request.post('/api/assets', { multipart: { files: {
    name: 'inline-caption.jpg', mimeType: 'image/jpeg', buffer: readFileSync('samples/photo-01.jpg'),
  } } })
  expect(uploaded.ok()).toBe(true)
  const file = (await uploaded.json())[0].file
  await page.reload()
  await page.getByTestId('tab-projects').click()
  await page.getByRole('button', { name: '新建空白项目' }).click()
  await page.getByTestId('tab-blocks').click()
  await page.getByTestId('kit-box').click()
  await page.getByTestId('kit-photos2').click()
  const box = page.getByTestId('canvas').locator('[data-block-type="box"]')
  const photos = box.locator('[data-block-type="photos"]')
  await page.getByTestId('tab-assets').click()
  await page.locator(`.asset img[src*="${file}"]`).click()
  const image = photos.locator('img:not([data-slot])')
  await expect(image).toHaveCount(1)
  const src = await image.getAttribute('src')
  await image.dblclick()
  const editor = photos.getByTestId('inline-block-text')
  await expect(editor).toBeVisible()
  await expect(box.getByTestId('inline-block-text')).toHaveCount(1)
  await editor.getByLabel('图注 1', { exact: true }).fill('双击修改的图注')
  await editor.getByRole('button', { name: '完成', exact: true }).click()
  await expect(editor).toHaveCount(0)
  await expect(photos).toContainText('双击修改的图注')
  await expect(image).toHaveAttribute('src', src!)
  await page.getByRole('button', { name: '撤销' }).click()
  await expect(photos).not.toContainText('双击修改的图注')
  await expect(image).toHaveAttribute('src', src!)
  await image.dblclick()
  await editor.getByLabel('图注 1', { exact: true }).fill('保存后仍保留图片')
  await expect(editor).toBeVisible()
  await expect(editor.locator('textarea').first()).toHaveValue('保存后仍保留图片')
  await page.keyboard.press('Escape')
  await expect(editor).toHaveCount(0)
  await expect(page.getByTestId('save-status')).toHaveText('已保存', { timeout: 10_000 })
  await page.reload()
  await expect(photos).toContainText('保存后仍保留图片')
  await expect(image).toHaveAttribute('src', src!)
})
