import { expect, test } from '@playwright/test'

test('compact toolbar preserves secondary actions in a dismissible disclosure', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const more = page.getByRole('button', { name: '更多', exact: true })
  const data = page.getByTestId('open-data')
  const models = page.getByTestId('open-ai-settings')
  await expect(more).toBeVisible()
  await expect(data).toBeHidden()
  await expect(models).toBeHidden()
  await expect(page.getByTestId('open-preview')).toBeVisible()
  await expect(page.getByTestId('open-export')).toBeVisible()
  await more.focus()
  await page.keyboard.press('Enter')
  await expect(more).toHaveAttribute('aria-expanded', 'true')
  await expect(data).toBeVisible()
  await expect(models).toBeVisible()
  const box = (await data.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(390)
  expect(box.height).toBeGreaterThanOrEqual(44)
  await page.keyboard.press('Escape')
  await expect(more).toBeFocused()
  await expect(data).toBeHidden()
  await more.click()
  await page.getByLabel('文章标题').click()
  await expect(data).toBeHidden()
  await more.click()
  await data.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(more).toBeFocused()
  await expect(data).toBeHidden()
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(more).toBeHidden()
  await expect(data).toBeVisible()
  await expect(models).toBeVisible()
})
