import { expect, test } from '@playwright/test'

test('saved and template component insertion has a keyboard action without removing pointer insertion', async ({ page }) => {
  const id = `component-keyboard-${Date.now()}`
  const now = Date.now()
  const doc = { id, title: 'Component insertion fixture', author: '', digest: '', themeId: 'minimal-magazine', createdAt: now, updatedAt: now, blocks: [{ id: 'original', type: 'heading', props: { title: 'Preserved heading', index: '', subtitle: '', variant: 'auto' } }] }
  expect((await page.request.put(`/api/projects/${id}`, { data: doc })).ok()).toBe(true)
  await page.route('**/api/projects', r => r.fulfill({ json: [{ id, title: doc.title }] }))
  await page.route('**/api/components', r => r.fulfill({ json: [{ id: 'keyboard-component', schema: 1, rev: 1, name: 'Keyboard component', kind: 'heading', tags: [], block: { id: 'saved-heading', type: 'heading', props: { title: 'Inserted saved heading', index: '01', subtitle: '', variant: 'auto' } }, fingerprint: 'synthetic', palette: [], fixedDecor: 0, stats: { texts: 1, photos: 0, bgPhotos: 0, chars: 22 }, text: 'Keyboard component', origin: { kind: 'original', title: 'Synthetic', via: 'block', attested: true }, createdAt: 1, updatedAt: 1 }] }))
  await page.route('**/api/templates', r => r.fulfill({ json: [{ id: 'keyboard-template', name: 'Keyboard template', createdAt: now, blocks: [{ id: 'template-block', type: 'html', props: { label: 'Template fragment', html: '<section style="border:1px solid #123456"><p>Inserted template fragment</p></section>' } }] }] }))
  await page.goto('/')
  await expect(page.locator('.title-input')).toHaveValue(doc.title)
  const canvas = page.getByTestId('canvas')
  const blocks = canvas.locator('.block[data-block-id]')
  await expect(blocks).toHaveCount(1)
  await page.getByTestId('tab-components').click()
  const saved = page.getByTestId('component-card').filter({ hasText: 'Keyboard component' })
  const action = saved.getByRole('button', { name: '插入组件：Keyboard component' })
  await expect(action).toBeVisible()
  await action.focus()
  await page.keyboard.press('Space')
  await expect(blocks).toHaveCount(2)
  await expect(canvas).toContainText('Inserted saved heading')
  await saved.getByTestId('component-insert').click()
  await expect(blocks).toHaveCount(3)
  await page.getByTestId('components-parts').click()
  const part = page.getByTestId('part-card').filter({ hasText: 'Template fragment' })
  const templateAction = part.getByRole('button', { name: '插入组件：Template fragment' })
  await templateAction.focus()
  await page.keyboard.press('Enter')
  await expect(blocks).toHaveCount(4)
  await expect(canvas).toContainText('Inserted template fragment')
  await expect(canvas.locator('[data-block-id="original"]')).toContainText('Preserved heading')
  await expect(page.getByTestId('save-status')).toHaveText('已保存')
  await page.reload()
  await expect(blocks).toHaveCount(4)
})
